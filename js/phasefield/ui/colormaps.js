// CPU versions of the GPU colour maps, used for the colour-bar legend.
// Must match cm_* in gpu/wgsl.js.

const poly = (c, x) => c[0].map((_, k) => c.reduceRight((acc, ck) => acc * x + ck[k], 0));

const VIRIDIS = [[0.2777273272, 0.0054073445, 0.3340998053], [0.1050930431, 1.4046135299, 1.3845901626], [-0.3308618287, 0.2148475595, 0.0950951630], [-4.6342304990, -5.7991009734, -19.3324409563], [6.2282699363, 14.1799333668, 56.6905526007], [4.7763849977, -13.7451453777, -65.3530326334], [-5.4354558559, 4.6458526122, 26.3124352496]];
const MAGMA = [[-0.0021364851, -0.0007496551, -0.0053861279], [0.2516605407, 0.6775232437, 2.4940265993], [8.3537172792, -3.5777195150, 0.3144679030], [-27.6687330858, 14.2647307810, -13.6492131881], [52.1761398123, -27.9436060717, 12.9441694424], [-50.7685253647, 29.0465828213, 4.2341529938], [18.6557050659, -11.4897735200, -5.6019615087]];

const clamp01 = (v) => Math.min(1, Math.max(0, v));
const smooth = (t) => t * t * (3 - 2 * t);
const mix = (a, b, t) => a.map((v, k) => v + (b[k] - v) * t);

function turbo(x) {
    const v4 = [1, x, x * x, x * x * x], v2 = [v4[2] * v4[2], v4[3] * v4[2]];
    const d4 = (w) => v4[0] * w[0] + v4[1] * w[1] + v4[2] * w[2] + v4[3] * w[3];
    const d2 = (w) => v2[0] * w[0] + v2[1] * w[1];
    return [
        d4([0.13572138, 4.61539260, -42.66032258, 132.13108234]) + d2([-152.94239396, 59.28637943]),
        d4([0.09140261, 2.19418839, 4.84296658, -14.18503333]) + d2([4.27729857, 2.82956604]),
        d4([0.10667330, 12.64194608, -60.58204836, 110.36276771]) + d2([-89.90310912, 27.34824973]),
    ];
}

export const COLORMAPS = {
    0: (x) => poly(VIRIDIS, x),
    1: (x) => poly(MAGMA, x),
    2: turbo,
    3: (x) => (x < 0.5 ? mix([0.230, 0.299, 0.754], [0.865, 0.865, 0.865], smooth(x * 2)) : mix([0.865, 0.865, 0.865], [0.706, 0.016, 0.150], smooth(x * 2 - 1))),
    4: (x) => [1.25 * x, 0.7812 * x, 0.4975 * x],
    5: (x) => [x, x, x],
};

export const CMAP_IDS = { viridis: 0, magma: 1, turbo: 2, coolwarm: 3, copper: 4, gray: 5 };

export function gradientCSS(id) {
    const f = COLORMAPS[id] || COLORMAPS[0];
    const stops = [];
    for (let i = 0; i <= 10; i++) {
        const c = f(i / 10).map((v) => Math.round(clamp01(v) * 255));
        stops.push(`rgb(${c.join(',')}) ${i * 10}%`);
    }
    return `linear-gradient(90deg, ${stops.join(', ')})`;
}
